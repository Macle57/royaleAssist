package com.macle.royaleassist.text

import kotlin.math.abs
import kotlin.math.floor

/**
 * The Unicode scripts the OCR and matching logic tells apart, replacing
 * `java.lang.Character.UnicodeScript` in common code. [COMMON] covers digits, punctuation,
 * symbols, combining marks and the letters Unicode assigns to no script (ー, 〆, ℂ, modifier
 * letters); [OTHER] is a letter of any script not listed here (Thai, Hebrew, ...), all lumped
 * together.
 */
enum class UScript {
    COMMON, LATIN, GREEK, CYRILLIC, ARABIC, DEVANAGARI, HAN, HIRAGANA, KATAKANA, HANGUL, OTHER;

    companion object {
        /** Script of a code point (a lone surrogate is [COMMON], as Java's UNKNOWN is skipped too). */
        fun of(cp: Int): UScript {
            var lo = 0
            var hi = RANGES.size / 3 - 1
            while (lo <= hi) {
                val mid = (lo + hi) ushr 1
                val start = RANGES[mid * 3]
                val end = RANGES[mid * 3 + 1]
                when {
                    cp < start -> hi = mid - 1
                    cp > end -> lo = mid + 1
                    else -> return entries[RANGES[mid * 3 + 2]]
                }
            }
            return if (isLetter(cp)) OTHER else COMMON
        }

        fun of(c: Char): UScript = of(c.code)
    }
}

/** True for letters, like `Character.isLetter(int)` (supplementary planes approximated by block). */
fun isLetter(cp: Int): Boolean {
    if (cp < 0x10000) return cp.toChar().isLetter()
    var i = 0
    while (i < SUPPLEMENTARY_LETTERS.size) {
        if (cp >= SUPPLEMENTARY_LETTERS[i] && cp <= SUPPLEMENTARY_LETTERS[i + 1]) return true
        i += 2
    }
    return false
}

/** The code points of [s] (surrogate pairs combined), like `String.codePoints()`. */
fun codePoints(s: String): IntArray {
    val out = IntArray(s.length)
    var n = 0
    var i = 0
    while (i < s.length) {
        val c = s[i]
        if (c.isHighSurrogate() && i + 1 < s.length && s[i + 1].isLowSurrogate()) {
            out[n++] = 0x10000 + ((c.code - 0xD800) shl 10) + (s[i + 1].code - 0xDC00)
            i += 2
        } else {
            out[n++] = c.code
            i++
        }
    }
    return out.copyOf(n)
}

