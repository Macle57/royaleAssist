/**
 * Two decimals with a '.', half-up (`"%.2f".format(x)` in the logs; String.format used the
 * device locale, so a German phone wrote "0,85").
 */
fun fmt2(x: Double): String {
    if (x.isNaN()) return "NaN"
    if (x.isInfinite()) return if (x > 0) "Infinity" else "-Infinity"
    val neg = x < 0
    val cents = floor(abs(x) * 100 + 0.5).toLong()
    val s = "${cents / 100}.${(cents % 100).toString().padStart(2, '0')}"
    return if (neg && cents != 0L) "-$s" else s
}

fun fmt2(x: Float): String = fmt2(x.toDouble())

