"""Generates shared/.../badge/BadgeData.kt: a 16x16 RGB descriptor of the inside of every clan badge.

The badges come from RoyaleAPI's cr-api-data / cr-api-assets (ids 16000000.. = the official API's
badgeId). Only the inside of the shield is kept: the frame's colour changes with the clan's war
league in game, the symbol and background do not.

Usage: python -I tools/badges/gen_badge_data.py <badge png dir> <alliance_badges.json> <out .kt>
  (png dir: one <name>.png per entry, from https://royaleapi.github.io/cr-api-assets/badges/<name>.png)
"""
import base64, json, sys
import cv2, numpy as np

N = 16
INNER = (0.24, 0.22, 0.76, 0.74)  # left, top, right, bottom fractions of the shield's alpha box


def box_avg(img, x0, y0, x1, y1):
    """Same cell bounds as BadgeMatcher.sample (integer cell edges, at least one pixel)."""
    out = np.zeros((N, N, 3))
    for j in range(N):
        ya = int(y0 + (y1 - y0) * j / N); yb = max(ya + 1, int(y0 + (y1 - y0) * (j + 1) / N))
        for i in range(N):
            xa = int(x0 + (x1 - x0) * i / N); xb = max(xa + 1, int(x0 + (x1 - x0) * (i + 1) / N))
            out[j, i] = img[ya:yb, xa:xb].reshape(-1, 3).mean(0)
    return out


def main(png_dir, meta_path, out_path):
    meta = sorted(json.load(open(meta_path, encoding="utf-8")), key=lambda b: b["id"])
    blob = bytearray(); ratios = []
    for b in meta:
        im = cv2.imread(f"{png_dir}/{b['name']}.png", cv2.IMREAD_UNCHANGED)
        ys, xs = np.where(im[:, :, 3] > 128)
        im = im[ys.min():ys.max() + 1, xs.min():xs.max() + 1]
        rgb = im[:, :, 2::-1].astype(float)  # BGRA -> RGB
        h, w = rgb.shape[:2]; ratios.append(w / h)
        d = box_avg(rgb, w * INNER[0], h * INNER[1], w * INNER[2], h * INNER[3])
        blob += bytes(np.clip(np.rint(d), 0, 255).astype(np.uint8).ravel())
    b64 = base64.b64encode(bytes(blob)).decode()
    chunks = [b64[i:i + 60000] for i in range(0, len(b64), 60000)]
    ids = ", ".join(str(b["id"]) for b in meta)
    names = ",\n        ".join('"' + b["name"] + '"' for b in meta)
    ar = float(np.median(ratios))
    with open(out_path, "w", encoding="utf-8", newline="\n") as f:
        f.write("// Generated by tools/badges/gen_badge_data.py. Do not edit.\n")
        f.write("package com.macle.royaleassist.badge\n\n")
        f.write("/** Clan badges: official API badge ids, RoyaleAPI asset names and 16x16 RGB inner descriptors. */\n")
        f.write("internal object BadgeData {\n")
        f.write(f"    const val SIZE = {N}\n")
        f.write(f"    const val INNER_LEFT = {INNER[0]}f\n    const val INNER_TOP = {INNER[1]}f\n")
        f.write(f"    const val INNER_RIGHT = {INNER[2]}f\n    const val INNER_BOTTOM = {INNER[3]}f\n")
        f.write(f"    /** Width over height of the shield (median; all badges are within 2 %). */\n")
        f.write(f"    const val ASPECT = {ar:.4f}f\n\n")
        f.write(f"    val ids = intArrayOf({ids})\n\n")
        f.write(f"    val names = arrayOf(\n        {names},\n    )\n\n")
        for i, c in enumerate(chunks):
            f.write(f'    private const val D{i} = "{c}"\n')
        f.write("\n    /** [ids].size * SIZE * SIZE * 3 bytes, RGB row-major, badge by badge. */\n")
        f.write("    @OptIn(kotlin.io.encoding.ExperimentalEncodingApi::class)\n")
        f.write("    val descriptors: ByteArray by lazy { kotlin.io.encoding.Base64.decode(" + " + ".join(f"D{i}" for i in range(len(chunks))) + ") }\n")
        f.write("}\n")
    print(f"{len(meta)} badges, {len(blob)} bytes, {len(chunks)} chunks, aspect {ar:.4f}")


if __name__ == "__main__":
    main(*sys.argv[1:4])
